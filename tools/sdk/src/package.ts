import { createHash } from "node:crypto";
import {
  isAppCatalogImageRole,
  appReleaseDescriptorSchema,
  appReleaseIdentitySchema,
  appOriginCoordinates,
  parseAppManifest,
  assertAppJson,
  type AppManifest,
  type AppReleaseDescriptor,
  type AppReleaseIdentity,
} from "../contracts/apps/index.js";
import { appPlatformLimits as limits } from "../contracts/limits.js";
import {
  packAppArchive,
  readAppArchive,
  type AppArchiveFiles,
} from "./archive.js";

export function appSha256(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}
export function canonicalAppJson(
  value: unknown,
  profile: "data" | "manifest" = "data",
): Uint8Array {
  const maxBytes =
    profile === "manifest" ? limits.manifestBytes : limits.jsonBytes;
  const nodes =
    profile === "manifest" ? limits.manifestJsonNodes : limits.jsonNodes;
  const normalize = (item: unknown): unknown => {
    if (Array.isArray(item)) return item.map(normalize);
    if (item && typeof item === "object")
      return Object.fromEntries(
        Object.entries(item)
          .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
          .map(([key, child]) => [key, normalize(child)]),
      );
    return item;
  };
  assertAppJson(value, maxBytes, { nodes, depth: limits.jsonDepth });
  const bytes = new TextEncoder().encode(
    `${JSON.stringify(normalize(value), null, 2)}\n`,
  );
  if (bytes.byteLength > maxBytes)
    throw new Error("Canonical JSON exceeds the byte budget.");
  return bytes;
}
export function readAppJson(
  bytes: Uint8Array,
  maxBytes: number = limits.jsonBytes,
  nodes: number = limits.jsonNodes,
): unknown {
  if (bytes.byteLength > maxBytes)
    throw new Error("JSON file exceeds the byte budget.");
  const value: unknown = JSON.parse(
    new TextDecoder("utf-8", { fatal: true }).decode(bytes),
  );
  assertAppJson(value, maxBytes, { nodes, depth: limits.jsonDepth });
  return value;
}
export function readAppManifestJson(bytes: Uint8Array): unknown {
  return readAppJson(bytes, limits.manifestBytes, limits.manifestJsonNodes);
}
const extensionTypes: Record<string, string> = {
  json: "application/json",
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  webp: "image/webp",
  txt: "text/plain",
  md: "text/plain",
};
export function validateAppFiles(
  manifest: AppManifest,
  files: AppArchiveFiles,
) {
  const declared = new Set([
    "manifest.json",
    ...manifest.assets.map((asset) => asset.path),
  ]);
  if (
    declared.size !== files.size ||
    [...files.keys()].some((path) => !declared.has(path))
  )
    throw new Error(
      "Every package file must have exactly one declared asset mapping.",
    );
  for (const asset of manifest.assets) {
    if (asset.path === "manifest.json" || !files.has(asset.path))
      throw new Error("Missing or reserved asset path.");
    if (
      /(^|\/)(node_modules|server|backend|bin|hooks)(\/|$)/i.test(asset.path) ||
      /(^|\/)package(?:-lock)?\.json$/i.test(asset.path)
    )
      throw new Error("Publisher backend/build files cannot be installed.");
    const extension = asset.path.split(".").pop()?.toLowerCase() ?? "";
    if (extensionTypes[extension] !== asset.mediaType)
      throw new Error("Unsupported asset extension/media type.");
    if (
      isAppCatalogImageRole(asset.role) &&
      !["image/png", "image/jpeg", "image/webp"].includes(asset.mediaType)
    )
      throw new Error("Catalog images require passive raster assets.");
  }
}
export function buildAppPackage(input: unknown, assets: AppArchiveFiles) {
  const manifest = parseAppManifest(input);
  const manifestBytes = canonicalAppJson(manifest, "manifest");
  const files = new Map(assets);
  if (files.has("manifest.json"))
    throw new Error("Manifest bytes are generated by the package tool.");
  files.set("manifest.json", manifestBytes);
  validateAppFiles(manifest, files);
  const archive = packAppArchive(files);
  return {
    manifest,
    manifestBytes,
    archive,
    artifactSha256: appSha256(archive),
    manifestSha256: appSha256(manifestBytes),
  };
}
export function describeAppRelease(
  built: ReturnType<typeof buildAppPackage>,
  identity: AppReleaseIdentity,
): AppReleaseDescriptor {
  identity = appReleaseIdentitySchema.parse(identity);
  if (identity.version !== built.manifest.package.version)
    throw new Error("Release/package version mismatch.");
  return appReleaseDescriptorSchema.parse({
    schemaVersion: "1.0",
    ...identity,
    artifact: {
      name: `${built.manifest.package.key}-${identity.version}.anvilapp`,
      bytes: built.archive.byteLength,
      sha256: built.artifactSha256,
    },
    manifestSha256: built.manifestSha256,
    assets: built.manifest.assets
      .filter((asset) => isAppCatalogImageRole(asset.role))
      .map((asset) => {
        const bytes = readAppArchive(built.archive).get(asset.path)!;
        return {
          path: asset.path,
          releaseName: `${asset.role}.${asset.path.split(".").pop()}`,
          sha256: appSha256(bytes),
          bytes: bytes.byteLength,
          mediaType: asset.mediaType,
        };
      }),
  });
}
export function verifyAppPackage(
  archive: Uint8Array,
  descriptorInput: unknown,
  sidecar: Uint8Array,
  expected: AppReleaseIdentity,
) {
  assertAppJson(descriptorInput);
  const descriptor = appReleaseDescriptorSchema.parse(descriptorInput);
  expected = appReleaseIdentitySchema.parse(expected);
  const actualOrigin = appOriginCoordinates(descriptor),
    expectedOrigin = appOriginCoordinates(expected);
  if (
    actualOrigin.provider !== expectedOrigin.provider ||
    actualOrigin.id !== expectedOrigin.id
  )
    throw new Error("Release identity mismatch: source origin.");
  if (actualOrigin.publisherId !== expectedOrigin.publisherId)
    throw new Error("Release identity mismatch: publisherId.");
  for (const key of ["releaseId", "commitSha", "version", "immutable"] as const)
    if (descriptor[key] !== expected[key])
      throw new Error(`Release identity mismatch: ${key}.`);
  if (
    archive.byteLength !== descriptor.artifact.bytes ||
    appSha256(archive) !== descriptor.artifact.sha256
  )
    throw new Error("Artifact bytes/digest mismatch.");
  if (
    sidecar.byteLength > limits.manifestBytes ||
    appSha256(sidecar) !== descriptor.manifestSha256
  )
    throw new Error("Release manifest digest mismatch.");
  const files = readAppArchive(archive);
  const manifestBytes = files.get("manifest.json");
  if (!manifestBytes || !Buffer.from(manifestBytes).equals(sidecar))
    throw new Error("Archive and release manifests differ.");
  const manifest = parseAppManifest(readAppManifestJson(manifestBytes));
  if (
    !Buffer.from(canonicalAppJson(manifest, "manifest")).equals(manifestBytes)
  )
    throw new Error("Manifest must use canonical SDK JSON encoding.");
  if (manifest.package.version !== descriptor.version)
    throw new Error("Manifest/release version mismatch.");
  validateAppFiles(manifest, files);
  const catalog = manifest.assets.filter((asset) =>
    isAppCatalogImageRole(asset.role),
  );
  if (descriptor.assets.length !== catalog.length)
    throw new Error("Catalog asset mapping mismatch.");
  const names = new Set<string>();
  const paths = new Set<string>();
  for (const asset of descriptor.assets) {
    const declared = catalog.find((item) => item.path === asset.path);
    const bytes = files.get(asset.path);
    if (
      names.has(asset.releaseName.toLowerCase()) ||
      paths.has(asset.path) ||
      !declared ||
      !bytes ||
      declared.mediaType !== asset.mediaType ||
      bytes.byteLength !== asset.bytes ||
      appSha256(bytes) !== asset.sha256
    )
      throw new Error("Catalog asset mapping/digest mismatch.");
    names.add(asset.releaseName.toLowerCase());
    paths.add(asset.path);
  }
  return { manifest, descriptor, files };
}
